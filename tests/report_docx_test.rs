fn seeded() -> (ReportContext, Vec<DiagramAsset>) {
    let store = Store::open_in_memory().unwrap();
    let id = common::seed_estate(&store);
    let report = ReportContext::build(&store, &id).unwrap();
    let mut diagrams = assets::build_overviews(&store, &id, &DiagramScope::default()).unwrap();
    diagrams.extend(assets::build_resource_diagrams(&store, &id).unwrap());
    (report, diagrams)
}

fn themed(theme: &str) -> BrandingContext {
    BrandingContext::resolve(
        &BrandingConfig {
            theme: theme.to_owned(),
            ..BrandingConfig::default()
        },
        None,
    )
    .unwrap()
}

fn archive_entry(bytes: &[u8], name: &str) -> String {
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(bytes)).unwrap();
    let mut entry = archive.by_name(name).unwrap();
    let mut content = String::new();
    entry.read_to_string(&mut content).unwrap();
    content
}

fn archive_contains_media(bytes: &[u8], expected: &[u8]) -> bool {
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(bytes)).unwrap();
    (0..archive.len()).any(|index| {
        let mut entry = archive.by_index(index).unwrap();
        if !entry.name().starts_with("word/media/") {
            return false;
        }
        let mut content = Vec::new();
        entry.read_to_end(&mut content).unwrap();
        content == expected
    })
}

fn archive_contains_media_with_corner(bytes: &[u8], expected: [u8; 4]) -> bool {
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(bytes)).unwrap();
    (0..archive.len()).any(|index| {
        let mut entry = archive.by_index(index).unwrap();
        if !entry.name().starts_with("word/media/") {
            return false;
        }
        let mut content = Vec::new();
        entry.read_to_end(&mut content).unwrap();
        image::load_from_memory(&content)
            .map(|image| image.to_rgba8().get_pixel(0, 0).0 == expected)
            .unwrap_or(false)
    })
}

#[test]
fn docx_document_contains_headings_findings_and_severity_shading() {
    let (report, diagrams) = seeded();
    let branding = BrandingContext::default();
    let high_fill = branding
        .tokens
        .palette
        .severity
        .high
        .fill
        .trim_start_matches('#');

    let bytes = docx::render(&report, &branding, &diagrams).unwrap();

    let document = archive_entry(&bytes, "word/document.xml");
    assert!(document.contains("Azure Estate Report"), "cover title");
    assert!(document.contains("Executive Summary"), "summary heading");
    assert!(document.contains("Findings"), "findings heading");
    assert!(
        document.contains("stprodapp01 allows public blob access"),
        "findings row"
    );
    // High-severity fill from the default theme's palette.
    assert!(document.contains(high_fill), "severity cell shading");
}

