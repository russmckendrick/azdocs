// Writes THIRD_PARTY_LICENSES.md: every production npm dependency the
// desktop bundle ships, with its version, licence and repository, from the
// installed package manifests. The Rust side has cargo-about; this is the
// same discipline for the frontend, and the file is bundled as a resource so
// the installed app carries it.
//
//     node scripts/frontend-licenses.mjs           # rewrite the report
//     node scripts/frontend-licenses.mjs --check   # fail if it is stale
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const desktopDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(desktopDir, "THIRD_PARTY_LICENSES.md");
const check = process.argv.includes("--check");

const manifest = JSON.parse(readFileSync(resolve(desktopDir, "package.json"), "utf8"));
const seen = new Map();

function manifestOf(name, from) {
  // pnpm keeps each package's dependencies beside its real directory under
  // node_modules/.pnpm/<pkg>/node_modules/, so a dependant's transitive
  // dependencies are siblings of its realpath; the root is the last resort.
  const candidates = [
    resolve(from, "node_modules", name, "package.json"),
    resolve(from, "..", name, "package.json"),
    resolve(desktopDir, "node_modules", name, "package.json"),
  ];
  for (const file of candidates) {
    if (existsSync(file)) return { file: realpathSync(file), data: JSON.parse(readFileSync(file, "utf8")) };
  }
  return undefined;
}

function licenseOf(data) {
  if (typeof data.license === "string") return data.license;
  if (data.license?.type) return data.license.type;
  if (Array.isArray(data.licenses)) return data.licenses.map((entry) => entry.type ?? entry).join(" OR ");
  return "UNKNOWN";
}

function walk(name, from) {
  const found = manifestOf(name, from);
  if (!found) {
    console.error(`dependency ${name} is not installed; run pnpm install`);
    process.exit(1);
  }
  const key = `${found.data.name}@${found.data.version}`;
  if (seen.has(key)) return;
  seen.set(key, {
    name: found.data.name,
    version: found.data.version,
    license: licenseOf(found.data),
    repository:
      typeof found.data.repository === "string"
        ? found.data.repository
        : (found.data.repository?.url ?? found.data.homepage ?? ""),
  });
  for (const dependency of Object.keys(found.data.dependencies ?? {})) {
    walk(dependency, dirname(found.file));
  }
}

for (const name of Object.keys(manifest.dependencies ?? {})) walk(name, desktopDir);

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const unknown = rows.filter((row) => row.license === "UNKNOWN");
if (unknown.length) {
  console.error(`licence unknown for: ${unknown.map((row) => row.name).join(", ")}`);
  process.exit(1);
}
const report = [
  "# Frontend third-party licences",
  "",
  "Production npm dependencies bundled into the azdocs desktop app, generated by",
  "`node scripts/frontend-licenses.mjs` from the installed package manifests.",
  "Development-only tooling (bundler, linter, test runner) is not shipped and",
  "is not listed. The Rust dependency report is generated by cargo-about at",
  "release time; see docs/development/releasing.md.",
  "",
  "| Package | Version | Licence | Source |",
  "|---|---|---|---|",
  ...rows.map((row) => `| ${row.name} | ${row.version} | ${row.license} | ${row.repository.replace(/^git\+/, "").replace(/\.git$/, "")} |`),
  "",
].join("\n");

if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== report) {
    console.error("THIRD_PARTY_LICENSES.md is stale; run node scripts/frontend-licenses.mjs");
    process.exit(1);
  }
  console.log(`THIRD_PARTY_LICENSES.md is current (${rows.length} packages)`);
} else {
  writeFileSync(target, report);
  console.log(`wrote THIRD_PARTY_LICENSES.md (${rows.length} packages)`);
}
